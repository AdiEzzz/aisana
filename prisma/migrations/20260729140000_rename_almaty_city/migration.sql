-- «Алматы (город)» → «Алматы».
-- Остальные города в справочнике записаны без уточнения в скобках
-- (Астана, Шымкент), из-за чего Алматы выбивался из общего вида
-- на дашборде, в фильтрах и на карте.
--
-- Область называется «Алматинская область» и не конфликтует с этим именем.
UPDATE "regions"
SET "name" = 'Алматы'
WHERE "code" = 'ALA'
  AND "name" = 'Алматы (город)'
  AND NOT EXISTS (SELECT 1 FROM "regions" WHERE "name" = 'Алматы');
