/**
 * Тематический справочник направлений.
 *
 * Это «знания о предметной области» портала: по каким признакам текст проекта
 * относится к тому или иному направлению. Признаки хранятся ОСНОВАМИ слов
 * (см. lib/search/text.ts) и фразами, на русском и английском сразу — поэтому
 * «завод», «заводы», «производство», «manufacturing» и «Industry 4.0»
 * приводят к одному направлению.
 *
 * Вес признака:
 *   strong — однозначный маркер отрасли («карьер», «руда»)
 *   medium — сильный, но не исключительный («датчик», «маршрут»)
 *   weak   — контекстная подсказка, работает только вместе с другими
 *
 * aliases — короткие точные обозначения («гмк», «hr»), которые нельзя искать
 * по началу слова, иначе они цепляют посторонние слова.
 */

